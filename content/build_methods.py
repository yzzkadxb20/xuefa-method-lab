def validate():
    ids = [m["id"] for m in METHODS]
    assert len(ids) == len(set(ids)), "duplicate ids"
    for m in METHODS:
        assert m["switch_to"] in ids, f"bad switch_to: {m['id']} -> {m['switch_to']}"
        assert len(m["steps"]) >= 3, m["id"]
        assert len(m["materials"]) >= 3, m["id"]
        assert m["evidence"] in {"A", "B", "C"}, m["id"]


def domain_stats():
    domains = {}
    for m in METHODS:
        for d in m["domains"]:
            domains[d] = domains.get(d, 0) + 1
    return domains


